"""Build reports/tables/m2_results.md from reports/m2/*.json (EXP-M2-001/002).

Usage:  PYTHONPATH=. python experiments/analysis/m2_tables.py
"""
from __future__ import annotations

import json
from pathlib import Path

R = Path("reports/m2")
CONDS = ["static_nominal", "occlusion_nominal", "dynamic_nominal", "dynamic_harsh"]
METHODS = ["overhead", "overhead+mobile"]


def f(x, nd=3):
    return "—" if x is None else f"{x:.{nd}f}"


def ci(c, scale=1.0, nd=3):
    return "—" if not c or c[0] != c[0] else f"[{c[0] * scale:.{nd}f}, {c[1] * scale:.{nd}f}]"


def main() -> None:
    lines = ["# M2 results (EXP-M2-001, held-out TEST seeds 2,000,000–2,000,009; 15 frames/episode)", "",
             "Generated by `experiments/analysis/m2_tables.py` from `reports/m2/*.json`. Simulation only.", "",
             "## Detection (per camera frame, IoU ≥ 0.5)", "",
             "| Condition | Method | TP | FP | FN | Precision | Recall | Mask IoU (mean) | Class acc. |",
             "|---|---|---|---|---|---|---|---|---|"]
    rows_pose, rows_trk, rows_succ = [], [], []
    for c in CONDS:
        for m in METHODS:
            p = R / f"m2_test_{c}_{m}.json"
            if not p.exists():
                continue
            r = json.loads(p.read_text())
            d = r["detection"]
            lines.append(f"| {c} | {m} | {d['tp']} | {d['fp']} | {d['fn']} | {f(d['precision'])} | {f(d['recall'])} | "
                         f"{f(d['mask_iou']['mean'] if d['mask_iou'] else None)} | {f(d['class_accuracy'])} |")
            for shape, v in r["pose"].items():
                if v["t_err_mm"]:
                    rows_pose.append(f"| {c} | {m} | {shape} | {v['t_err_mm']['n']} | {f(v['t_err_mm']['median'], 2)} | "
                                     f"{f(v['t_err_mm']['p90'], 2)} | "
                                     f"{f(v['r_err_deg']['median'], 2) if v['r_err_deg'] else '— (sym.)'} | "
                                     f"{f(v['add_s_mm']['median'], 2)} | {f(v['add_s_mm']['p90'], 2)} |")
            t, o = r["tracking"], r["occlusion_recovery"]
            tm = json.loads((R / f"m2_test_{c}_{m}_timing.json").read_text())
            rows_trk.append(f"| {c} | {m} | {f(t['MOTA'])} | {ci(t['MOTA_ci95_over_episodes'])} | {t['id_switches']} | "
                            f"{t['fragmentations']} | {t['fn']} | {t['fp']} | {f(t['MOTP_mm'], 2)} | "
                            f"{o['recovered_same_id']}/{o['events']} | {f(o['latency_frames_median'], 1)} | "
                            f"{tm['perceive_s']['median_ms']:.0f} |")
            rows_succ.append(f"| {c} | {m} | {f(r['pose_success_rate_1cm_5deg'])} |")
    lines += ["", "## Pose (matched detections; symmetry-aware)", "",
              "| Condition | Method | Shape | n | t err med (mm) | t err p90 (mm) | rot err med (deg) | ADD-S med (mm) | ADD-S p90 (mm) |",
              "|---|---|---|---|---|---|---|---|---|"] + rows_pose
    lines += ["", "### Pose success rate (t < 1 cm and symmetry-aware r < 5°; spheres: translation only)", "",
              "| Condition | Method | Success |", "|---|---|---|"] + rows_succ
    lines += ["", "## Tracking (CLEAR-MOT, 3D, match ≤ 5 cm, class-agnostic)", "",
              "| Condition | Method | MOTA | MOTA 95% CI (episodes) | ID sw. | Frag. | FN | FP | MOTP (mm) | Recovered same ID / hidden events | Recovery latency (frames, median) | Perception median ms / camera frame |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"] + rows_trk
    cs = R / "calib_sweep.json"
    if cs.exists():
        s = json.loads(cs.read_text())
        lines += ["", "## Calibration drift sweep (EXP-M2-002, 10 test seeds per level)", "",
                  ("| Drift (deg, nominal) | True drift (deg, mean) | Reproj. RMS overhead (px) | Reproj. RMS mobile (px) | "
                   "PnP rot err overhead / mobile (deg) | Triangulation err (mm) | Object loc. err, overhead (mm) |"),
                  "|---|---|---|---|---|---|---|"]
        for lvl, v in s.items():
            lines.append(f"| {lvl} | {v['overhead_true_drift_deg']['mean']:.2f} | {v['overhead_reproj_px']['mean']:.2f} | "
                         f"{v['mobile_reproj_px']['mean']:.2f} | {v['overhead_pnp_rot_err_deg']['mean']:.2f} / "
                         f"{v['mobile_pnp_rot_err_deg']['mean']:.2f} | {v['triangulation_err_mm']['mean']:.1f} | "
                         f"{v['object_loc_err_mm']['mean']:.1f} |")
    out = Path("reports/tables/m2_results.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
